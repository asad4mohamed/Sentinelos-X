import { useMemo } from 'react';
import { Link } from 'react-router-dom';
import { Bar, BarChart, CartesianGrid, Cell, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { Activity, AlertOctagon, AlertTriangle, CheckCircle2, CircleSlash, Gauge, Radar, RotateCw, Server, Siren } from 'lucide-react';
import { useSentinel } from '../../hooks/useSentinelData';
import { chronological, healthCounts, healthScore, riskSummary, type RiskLevel } from '../../lib/derive';
import { EmptyState, MetricCard, Panel } from '../../components/ui';
import { PageGate } from '../../components/PageGate';
import { HEALTH_META, RealBadge, SeverityBadge, SimBadge, StatusBadge } from '../../components/StatusBadge';
import { SensorPanel } from './SensorPanel';
import { Timeline } from '../../components/Timeline';
import { SimulationLauncher } from '../../components/SimulationLauncher';
import { Sparkline } from '../../components/Sparkline';
import { fmtDateTime, relTime } from '../../lib/format';
import { scenarioLabel } from '../incidents/IncidentsPage';

const RISK: Record<RiskLevel, { label: string; cls: string }> = {
  low: { label: 'Low', cls: 'border-emerald-500/40 text-emerald-300' },
  elevated: { label: 'Elevated', cls: 'border-amber-500/40 text-amber-300' },
  high: { label: 'High', cls: 'border-orange-500/50 text-orange-300' },
  severe: { label: 'Severe', cls: 'border-red-500/50 text-red-300' },
};

function FleetTelemetry() {
  const { metrics, simulation } = useSentinel();
  const series = useMemo(() => {
    const byTick = new Map<bigint, { lat: number; err: number; rpm: number; n: number }>();
    for (const m of metrics) {
      if (m.source !== 'simulation_engine') continue;
      const t = byTick.get(m.tick) ?? { lat: 0, err: 0, rpm: 0, n: 0 };
      t.lat += m.latencyMs;
      t.err += m.errorRate;
      t.rpm += m.requestRpm;
      t.n++;
      byTick.set(m.tick, t);
    }
    return [...byTick.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)).slice(-30).map(([, v]) => ({ lat: v.lat / v.n, err: (v.err / v.n) * 100, rpm: v.rpm }));
  }, [metrics]);
  return (
    <Panel title={<span className="inline-flex items-center gap-1.5"><Activity className="size-3.5" /> Fleet telemetry <span className="normal-case tracking-normal text-violet-300">· synthetic</span></span>}>
      {series.length < 2 ? (
        <p className="text-xs text-slate-500">{simulation?.telemetryEnabled === false ? 'Built-in telemetry is disabled in Settings.' : 'Waiting for simulation engine ticks…'}</p>
      ) : (
        <div className="grid grid-cols-3 gap-3">
          <Sparkline label="Avg latency" values={series.map(s => s.lat)} color="#22d3ee" format={v => `${v.toFixed(0)} ms`} />
          <Sparkline label="Avg error rate" values={series.map(s => s.err)} color="#f87171" format={v => `${v.toFixed(1)}%`} />
          <Sparkline label="Total requests" values={series.map(s => s.rpm)} color="#34d399" format={v => `${(v / 1000).toFixed(1)}k/min`} />
        </div>
      )}
      <p className="mt-2 text-[11px] text-slate-500">Generated by the built-in simulation engine in SpacetimeDB{simulation ? ` · tick #${String(simulation.tickCount)} every ${simulation.intervalMs / 1000}s` : ''}. Not production telemetry.</p>
    </Panel>
  );
}

function Overview() {
  const { assets, incidents, events, assetById, incidentAssets } = useSentinel();
  const counts = useMemo(() => healthCounts(assets), [assets]);
  const score = useMemo(() => healthScore(assets), [assets]);
  const risk = useMemo(() => riskSummary(incidents, assets), [incidents, assets]);
  const active = incidents.filter(i => i.status !== 'resolved');
  const recentIncidents = useMemo(() => [...incidents].sort((a, b) => (a.createdAt.microsSinceUnixEpoch < b.createdAt.microsSinceUnixEpoch ? 1 : -1)).slice(0, 5), [incidents]);
  const recent = useMemo(() => chronological(events).slice(-12).reverse(), [events]);
  const chartData = (['healthy', 'degraded', 'critical', 'offline', 'recovering'] as const).map(h => ({ name: h, count: counts[h], fill: HEALTH_META[h].hex }));
  const byEnv = useMemo(() => {
    const m = new Map<string, (typeof assets)[number][]>();
    for (const a of assets) m.set(a.environment, [...(m.get(a.environment) ?? []), a]);
    return [...m.entries()].sort();
  }, [assets]);
  const impactedNow = (id: bigint) => incidentAssets.filter(ia => ia.incidentId === id && ia.impactStatus !== 'recovered').length;

  if (assets.length === 0) {
    return (
      <Panel>
        <EmptyState title="No virtual infrastructure is loaded. Initialize the demo environment." hint="An Incident Commander can initialize it from Settings → Environment. New connections also seed it automatically." />
      </Panel>
    );
  }
  const scoreTone = score >= 90 ? 'text-emerald-300' : score >= 60 ? 'text-amber-300' : 'text-red-300';

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-xl font-semibold text-slate-50">Operations overview</h1>
          <p className="text-sm text-slate-400">Live state of the synthetic digital twin, streamed from SpacetimeDB.</p>
        </div>
        <SimulationLauncher />
      </div>

      <div className={`panel flex flex-wrap items-center gap-4 border px-4 py-3 ${RISK[risk.level].cls}`} role="status" aria-label="System risk summary">
        <Gauge className="size-6 shrink-0" aria-hidden />
        <div>
          <div className="text-[11px] font-semibold tracking-[0.12em] text-slate-400 uppercase">Current system risk</div>
          <div className="text-xl font-semibold">{RISK[risk.level].label}</div>
        </div>
        <ul className="flex flex-1 flex-wrap gap-x-4 gap-y-1 text-sm text-slate-300">
          {risk.reasons.map(r => (
            <li key={r}>• {r}</li>
          ))}
        </ul>
        <div className="text-right">
          <div className="text-[11px] text-slate-500 uppercase">Health score</div>
          <div className={`text-xl font-semibold tabular-nums ${scoreTone}`}>{score}%</div>
        </div>
      </div>

      <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <MetricCard label="Monitored services" value={counts.total} icon={Server} />
        <MetricCard label="Healthy" value={counts.healthy} icon={CheckCircle2} tone="text-emerald-300" />
        <MetricCard label="Degraded" value={counts.degraded} icon={AlertTriangle} tone="text-amber-300" />
        <MetricCard label="Critical" value={counts.critical} icon={AlertOctagon} tone="text-red-300" hint="Root causes" />
        <MetricCard label="Offline" value={counts.offline} icon={CircleSlash} tone="text-slate-300" hint="Dependency-induced" />
        <MetricCard label="Recovering" value={counts.recovering} icon={RotateCw} tone="text-sky-300" />
        <MetricCard label="At risk" value={counts.atRisk} icon={Radar} tone="text-violet-300" hint="Potentially exposed" />
        <MetricCard label="Active incidents" value={active.length} icon={Siren} tone={active.length ? 'text-red-300' : 'text-slate-300'} />
      </div>

      <SensorPanel />

      <div className="grid gap-4 xl:grid-cols-3">
        <Panel title="Infrastructure health">
          <div className="h-44" role="img" aria-label={`Service health: ${counts.healthy} healthy, ${counts.degraded} degraded, ${counts.critical} critical, ${counts.offline} offline, ${counts.recovering} recovering`}>
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={chartData} margin={{ top: 8, right: 8, left: -24, bottom: 0 }}>
                <CartesianGrid stroke="#1c2c44" vertical={false} />
                <XAxis dataKey="name" stroke="#64748b" fontSize={10} tickLine={false} />
                <YAxis allowDecimals={false} stroke="#64748b" fontSize={11} tickLine={false} />
                <Tooltip cursor={{ fill: '#132033' }} contentStyle={{ background: '#0a1220', border: '1px solid #1c2c44', fontSize: 12 }} />
                <Bar dataKey="count" radius={[3, 3, 0, 0]} isAnimationActive={false}>
                  {chartData.map(d => (
                    <Cell key={d.name} fill={d.fill} />
                  ))}
                </Bar>
              </BarChart>
            </ResponsiveContainer>
          </div>
          <div className="mt-3 space-y-1.5">
            {byEnv.map(([env, list]) => (
              <div key={env} className="flex items-center gap-2 text-xs">
                <span className="w-32 truncate text-slate-400">{env}</span>
                <div className="flex flex-1 gap-0.5">
                  {list.map(a => (
                    <Link key={a.assetId} to="/twin" title={`${a.name}: ${a.healthStatus}${a.impactType === 'exposed' ? ' (at risk)' : ''}`} className="h-2 flex-1 rounded-sm" style={{ background: a.impactType === 'exposed' && a.healthStatus === 'healthy' ? '#a78bfa' : (HEALTH_META[a.healthStatus]?.hex ?? '#475569') }} />
                  ))}
                </div>
              </div>
            ))}
          </div>
        </Panel>

        <Panel title="Recent incidents" bodyClass="p-0">
          {recentIncidents.length === 0 ? (
            <EmptyState title="No active incidents. Launch a synthetic scenario to test the environment." />
          ) : (
            <ul className="divide-y divide-ink-800">
              {recentIncidents.map(i => (
                <li key={String(i.incidentId)}>
                  <Link to={`/incidents/${i.incidentId}`} className="block px-4 py-2.5 hover:bg-ink-800">
                    <div className="flex flex-wrap items-center gap-1.5">
                      <span className="font-mono text-xs text-slate-500">INC-{String(i.incidentId)}</span>
                      <SeverityBadge severity={i.severity} />
                      <StatusBadge status={i.status} />
                      {i.isSimulation ? <SimBadge /> : <RealBadge />}
                    </div>
                    <div className="mt-0.5 truncate text-sm text-slate-100">{i.title}</div>
                    <div className="text-xs text-slate-500">
                      {scenarioLabel(i.scenarioType)} · {assetById.get(i.initialAssetId)?.name ?? i.initialAssetId} · {impactedNow(i.incidentId)} impacted · {fmtDateTime(i.createdAt)} · updated {relTime(i.updatedAt)}
                    </div>
                  </Link>
                </li>
              ))}
            </ul>
          )}
        </Panel>

        <Panel title="Recent events" bodyClass="max-h-96 overflow-y-auto p-4">
          {recent.length ? <Timeline events={recent} assetById={assetById} showIncident compact /> : <EmptyState title="No events yet" />}
        </Panel>
      </div>
      <FleetTelemetry />
    </div>
  );
}

export function OverviewPage() {
  return (
    <PageGate>
      <Overview />
    </PageGate>
  );
}
