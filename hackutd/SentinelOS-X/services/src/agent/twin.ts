// Read-only, SDK-independent view of the digital twin used by agent tools.
// Built from the agent's SpacetimeDB subscription cache at runtime, or from
// plain objects in tests.
import type { DbConnection } from '../module_bindings/index';

export interface TwinAsset {
  assetId: string;
  name: string;
  assetType: string;
  environment: string;
  criticality: string;
  healthStatus: string;
  operationalStatus: string;
  impactType: string;
  impactCausedBy: string | null;
  directFailure: string;
  directIncidentId: string | null;
}
export interface TwinEdge {
  dependentAssetId: string;
  requiredAssetId: string;
  dependencyType: string;
  rationale: string;
}
export interface TwinIncident {
  incidentId: string;
  title: string;
  severity: string;
  status: string;
  scenarioType: string;
  initialAssetId: string;
  isSimulation: boolean;
  createdAt: string;
}
export interface TwinImpact {
  assetId: string;
  impactType: string;
  impactStatus: string;
  peakStatus: string;
  depth: number;
  causedByAssetId: string | null;
}
export interface TwinEvent {
  timestamp: string;
  eventType: string;
  actorName: string;
  description: string;
  assetId: string | null;
}
export interface TwinSample {
  latencyMs: number;
  errorRate: number;
  cpuPct: number;
  throughputRpm: number;
  timestamp: string;
}
export interface TwinRecovery {
  recoveryId: string;
  assetId: string;
  status: string;
  plan: string;
}

export interface TwinEvidence {
  evidenceId: string;
  assetId: string;
  kind: string;
  title: string;
  detail: string;
  severity: string;
  indicators: { key: string; value: string }[];
  observedAt: string;
  /** true = generated by the simulation; false = measured by real hardware. */
  synthetic: boolean;
}
export interface TwinSensorNode {
  nodeId: string;
  assetId: string;
  name: string;
  sensorModel: string;
  tempLimitC: number;
  humidityLimitPct: number;
  status: string;
}
export interface TwinSensorReading {
  tempC: number;
  humidityPct: number;
  timestamp: string;
}

export interface TwinView {
  assets(): TwinAsset[];
  edges(): TwinEdge[];
  incident(id: string): TwinIncident | undefined;
  impacts(incidentId: string): TwinImpact[];
  events(incidentId: string): TwinEvent[];
  telemetry(assetId: string): TwinSample[];
  recoveries(incidentId: string): TwinRecovery[];
  evidence(incidentId: string): TwinEvidence[];
  sensorNodeFor(assetId: string): TwinSensorNode | undefined;
  sensorReadings(nodeId: string): TwinSensorReading[];
}

const iso = (t: { toDate(): Date }) => t.toDate().toISOString();

export function twinFromConnection(conn: DbConnection): TwinView {
  return {
    assets: () =>
      [...conn.db.asset.iter()].map(a => ({
        assetId: a.assetId,
        name: a.name,
        assetType: a.assetType,
        environment: a.environment,
        criticality: a.criticality,
        healthStatus: a.healthStatus,
        operationalStatus: a.operationalStatus,
        impactType: a.impactType,
        impactCausedBy: a.impactCausedBy ?? null,
        directFailure: a.directFailure,
        directIncidentId: a.directIncidentId === undefined ? null : String(a.directIncidentId),
      })),
    edges: () =>
      [...conn.db.dependency.iter()].map(d => ({
        dependentAssetId: d.dependentAssetId,
        requiredAssetId: d.requiredAssetId,
        dependencyType: d.dependencyType,
        rationale: d.rationale,
      })),
    incident: id => {
      const i = [...conn.db.incident.iter()].find(x => String(x.incidentId) === id);
      return i
        ? {
            incidentId: String(i.incidentId),
            title: i.title,
            severity: i.severity,
            status: i.status,
            scenarioType: i.scenarioType,
            initialAssetId: i.initialAssetId,
            isSimulation: i.isSimulation,
            createdAt: iso(i.createdAt),
          }
        : undefined;
    },
    impacts: id =>
      [...conn.db.incidentAsset.iter()]
        .filter(x => String(x.incidentId) === id)
        .map(x => ({
          assetId: x.assetId,
          impactType: x.impactType,
          impactStatus: x.impactStatus,
          peakStatus: x.peakStatus,
          depth: x.depth,
          causedByAssetId: x.causedByAssetId ?? null,
        })),
    events: id =>
      [...conn.db.incidentEvent.iter()]
        .filter(e => String(e.incidentId) === id)
        .sort((a, b) => (a.eventId < b.eventId ? -1 : 1))
        .map(e => ({ timestamp: iso(e.timestamp), eventType: e.eventType, actorName: e.actorName, description: e.description, assetId: e.assetId ?? null })),
    telemetry: assetId =>
      [...conn.db.telemetrySample.iter()]
        .filter(s => s.assetId === assetId)
        .sort((a, b) => (a.sampleId < b.sampleId ? -1 : 1))
        .map(s => ({ latencyMs: s.latencyMs, errorRate: s.errorRate, cpuPct: s.cpuPct, throughputRpm: s.throughputRpm, timestamp: iso(s.timestamp) })),
    recoveries: id =>
      [...conn.db.recoveryAction.iter()]
        .filter(r => String(r.incidentId) === id)
        .map(r => ({ recoveryId: String(r.recoveryId), assetId: r.assetId, status: r.status, plan: r.plan })),
    evidence: id =>
      [...conn.db.incidentEvidence.iter()]
        .filter(e => String(e.incidentId) === id)
        .sort((a, b) => (a.evidenceId < b.evidenceId ? -1 : 1))
        .map(e => ({
          evidenceId: String(e.evidenceId),
          assetId: e.assetId,
          kind: e.kind,
          title: e.title,
          detail: e.detail,
          severity: e.severity,
          indicators: e.indicators.map(i => ({ key: i.key, value: i.value })),
          observedAt: iso(e.observedAt),
          synthetic: e.synthetic,
        })),
    sensorNodeFor: assetId => {
      const n = [...conn.db.sensorNode.iter()].find(x => x.assetId === assetId);
      return n
        ? { nodeId: n.nodeId, assetId: n.assetId, name: n.name, sensorModel: n.sensorModel, tempLimitC: n.tempLimitC, humidityLimitPct: n.humidityLimitPct, status: n.status }
        : undefined;
    },
    sensorReadings: nodeId =>
      [...conn.db.sensorReading.iter()]
        .filter(r => r.nodeId === nodeId)
        .sort((a, b) => (a.readingId < b.readingId ? -1 : 1))
        .map(r => ({ tempC: r.tempC, humidityPct: r.humidityPct, timestamp: iso(r.timestamp) })),
  };
}
