// Tools exposed to the Nemotron agent. All are read-only over the twin except
// report_finding / recommend_recovery, which only *record* structured output
// (validated again server-side). No tool can change infrastructure state, and
// none executes commands or touches the network.
import { computeImpacts, type DependencyType, type ImpactLevel } from '../../../spacetime/src/propagation';
import type { ToolSpec } from './llm';
import type { TwinView } from './twin';

export interface FindingDraft {
  kind: 'finding' | 'recommendation';
  summary: string;
  evidence: string;
  assetId: string | null;
  confidence: 'low' | 'medium' | 'high';
}

export interface ToolResult {
  ok: boolean;
  output: unknown;
  finding?: FindingDraft;
}

const obj = (properties: Record<string, unknown>, required: string[] = []) => ({ type: 'object', properties, required, additionalProperties: false });
const str = (description: string, extra: Record<string, unknown> = {}) => ({ type: 'string', description, ...extra });

export const TOOL_SPECS: ToolSpec[] = [
  { type: 'function', function: { name: 'get_incident', description: 'Incident summary: title, severity, status, initial asset, and every affected asset with impact type (direct/cascade), hop depth and cause.', parameters: obj({}) } },
  { type: 'function', function: { name: 'get_asset', description: 'Full state of one asset including criticality, health, impact, and latest synthetic telemetry.', parameters: obj({ asset_id: str('Asset id, e.g. primary-db') }, ['asset_id']) } },
  { type: 'function', function: { name: 'get_dependencies', description: 'What an asset requires and which assets require it, with edge type (required/noncritical/optional) and rationale.', parameters: obj({ asset_id: str('Asset id') }, ['asset_id']) } },
  { type: 'function', function: { name: 'get_timeline', description: 'Most recent incident timeline events, oldest first.', parameters: obj({ limit: { type: 'integer', minimum: 1, maximum: 50, description: 'Max events (default 25)' } }) } },
  { type: 'function', function: { name: 'get_telemetry', description: 'Synthetic telemetry statistics (latency, error rate, CPU, throughput) over the recent window for one asset.', parameters: obj({ asset_id: str('Asset id') }, ['asset_id']) } },
  { type: 'function', function: { name: 'get_evidence', description: 'Evidence recorded for this incident. Each item says whether it was MEASURED by real hardware (source "measured") or generated by the simulation (source "synthetic"), with its indicators.', parameters: obj({}) } },
  { type: 'function', function: { name: 'get_sensor_readings', description: 'REAL readings from the physical sensor attached to an asset: statistics, configured limits and the most recent raw readings. Only exists for physical-environment assets.', parameters: obj({ asset_id: str('Asset id of a physical sensor asset, e.g. env-uno-r4-01') }, ['asset_id']) } },
  { type: 'function', function: { name: 'simulate_recovery', description: 'Deterministic what-if: recompute the dependency graph as if the injected failure on the given asset were cleared. Returns which assets would return to healthy and which stay impacted.', parameters: obj({ asset_id: str('A directly failed asset id') }, ['asset_id']) } },
  { type: 'function', function: { name: 'simulate_failure', description: 'Deterministic what-if: blast radius if the given asset(s) additionally went offline. Use to assess risk of further spread.', parameters: obj({ asset_ids: { type: 'array', items: { type: 'string' }, minItems: 1, maxItems: 5 } }, ['asset_ids']) } },
  { type: 'function', function: { name: 'report_finding', description: 'Record an investigation finding backed by tool evidence.', parameters: obj({ summary: str('One-sentence finding', { maxLength: 400 }), evidence: str('Which tool outputs support it', { maxLength: 1200 }), asset_id: str('Related asset id, if any'), confidence: { type: 'string', enum: ['low', 'medium', 'high'] } }, ['summary', 'evidence', 'confidence']) } },
  { type: 'function', function: { name: 'recommend_recovery', description: 'Recommend restoring a ROOT-CAUSE (directly failed) asset. Humans must approve; it is never executed automatically.', parameters: obj({ asset_id: str('Directly failed asset id'), rationale: str('Why and in what order, citing evidence', { maxLength: 400 }), evidence: str('Supporting tool outputs', { maxLength: 1200 }), confidence: { type: 'string', enum: ['low', 'medium', 'high'] } }, ['asset_id', 'rationale', 'confidence']) } },
];

const CONF = new Set(['low', 'medium', 'high']);

function stats(xs: number[]) {
  if (xs.length === 0) return null;
  const sorted = [...xs].sort((a, b) => a - b);
  const r = (n: number) => Math.round(n * 1000) / 1000;
  return { min: r(sorted[0]!), avg: r(xs.reduce((a, b) => a + b, 0) / xs.length), max: r(sorted[sorted.length - 1]!), last: r(xs[xs.length - 1]!) };
}

function directFailures(twin: TwinView) {
  const m = new Map<string, Exclude<ImpactLevel, 'healthy'>>();
  for (const a of twin.assets()) if (a.directFailure === 'offline' || a.directFailure === 'degraded') m.set(a.assetId, a.directFailure);
  return m;
}

function impactTable(twin: TwinView, failures: Map<string, Exclude<ImpactLevel, 'healthy'>>) {
  const edges = twin.edges().map(e => ({ ...e, dependencyType: e.dependencyType as DependencyType }));
  return computeImpacts(twin.assets().map(a => a.assetId), edges, failures);
}

export function executeTool(twin: TwinView, incidentId: string, name: string, args: Record<string, unknown>): ToolResult {
  const assets = new Map(twin.assets().map(a => [a.assetId, a]));
  const needAsset = (key = 'asset_id') => {
    const id = String(args[key] ?? '');
    const a = assets.get(id);
    if (!a) throw new Error(`Unknown asset '${id}'. Known: ${[...assets.keys()].join(', ')}`);
    return a;
  };
  try {
    switch (name) {
      case 'get_incident': {
        const inc = twin.incident(incidentId);
        if (!inc) throw new Error(`Incident ${incidentId} not found`);
        const recoveries = twin.recoveries(incidentId);
        return {
          ok: true,
          output: {
            ...inc,
            affected: twin.impacts(incidentId).map(i => ({ ...i, name: assets.get(i.assetId)?.name, criticality: assets.get(i.assetId)?.criticality, currentHealth: assets.get(i.assetId)?.healthStatus })),
            recoveryRequests: recoveries,
          },
        };
      }
      case 'get_asset': {
        const a = needAsset();
        if (a.assetType === 'environment_sensor') {
          return { ok: true, output: { ...a, source: 'physical_sensor', note: 'Physical-environment asset measured by real hardware. Use get_sensor_readings for its data.' } };
        }
        const samples = twin.telemetry(a.assetId);
        return { ok: true, output: { ...a, latestTelemetry: samples[samples.length - 1] ?? 'no telemetry (generator not running)' } };
      }
      case 'get_evidence': {
        const rows = twin.evidence(incidentId).slice(0, 24);
        return {
          ok: true,
          output: {
            incident: incidentId,
            count: rows.length,
            evidence: rows.map(e => ({ id: e.evidenceId, source: e.synthetic ? 'synthetic' : 'measured', asset: e.assetId, kind: e.kind, title: e.title, detail: e.detail, severity: e.severity, indicators: Object.fromEntries(e.indicators.map(i => [i.key, i.value])), observedAt: e.observedAt })),
          },
        };
      }
      case 'get_sensor_readings': {
        const a = needAsset();
        const node = twin.sensorNodeFor(a.assetId);
        if (!node) return { ok: true, output: { asset: a.assetId, note: 'No physical sensor is attached to this asset. Its telemetry, if any, is synthetic.' } };
        const rs = twin.sensorReadings(node.nodeId);
        if (rs.length === 0) return { ok: true, output: { asset: a.assetId, node: node.nodeId, status: node.status, note: 'No readings have been recorded for this node.' } };
        return {
          ok: true,
          output: {
            asset: a.assetId,
            node: node.nodeId,
            source: 'physical_sensor',
            sensor: node.sensorModel,
            status: node.status,
            limits: { tempC: node.tempLimitC, humidityPct: node.humidityLimitPct },
            readings: rs.length,
            window: { from: rs[0]!.timestamp, to: rs[rs.length - 1]!.timestamp },
            tempC: stats(rs.map(x => x.tempC)),
            humidityPct: stats(rs.map(x => x.humidityPct)),
            recent: rs.slice(-12).map(x => ({ at: x.timestamp, tempC: x.tempC, humidityPct: x.humidityPct })),
            note: 'Measured values. A sensor shows what happened, not why.',
          },
        };
      }
      case 'get_dependencies': {
        const a = needAsset();
        const edges = twin.edges();
        return {
          ok: true,
          output: {
            asset: a.assetId,
            requires: edges.filter(e => e.dependentAssetId === a.assetId).map(e => ({ asset: e.requiredAssetId, type: e.dependencyType, health: assets.get(e.requiredAssetId)?.healthStatus, rationale: e.rationale })),
            requiredBy: edges.filter(e => e.requiredAssetId === a.assetId).map(e => ({ asset: e.dependentAssetId, type: e.dependencyType, health: assets.get(e.dependentAssetId)?.healthStatus })),
          },
        };
      }
      case 'get_timeline': {
        const limit = Math.min(50, Math.max(1, Number(args.limit ?? 25) || 25));
        return { ok: true, output: twin.events(incidentId).slice(-limit) };
      }
      case 'get_telemetry': {
        const a = needAsset();
        if (a.assetType === 'environment_sensor') {
          return { ok: true, output: { asset: a.assetId, note: 'This is a physical-environment asset with no synthetic telemetry. Use get_sensor_readings for its real measurements.' } };
        }
        const s = twin.telemetry(a.assetId);
        if (s.length === 0) return { ok: true, output: { asset: a.assetId, note: 'No telemetry samples (telemetry generator not running or not authorized).' } };
        return {
          ok: true,
          output: {
            asset: a.assetId,
            source: 'synthetic',
            samples: s.length,
            window: { from: s[0]!.timestamp, to: s[s.length - 1]!.timestamp },
            latencyMs: stats(s.map(x => x.latencyMs)),
            errorRate: stats(s.map(x => x.errorRate)),
            cpuPct: stats(s.map(x => x.cpuPct)),
            throughputRpm: stats(s.map(x => x.throughputRpm)),
          },
        };
      }
      case 'simulate_recovery': {
        const a = needAsset();
        const failures = directFailures(twin);
        if (!failures.has(a.assetId)) throw new Error(`${a.assetId} has no injected failure; only root-cause assets can be recovered`);
        const before = impactTable(twin, failures);
        failures.delete(a.assetId);
        const after = impactTable(twin, failures);
        const restored = [...before.values()].filter(i => i.level !== 'healthy' && after.get(i.assetId)?.level === 'healthy').map(i => i.assetId);
        const stillImpacted = [...after.values()].filter(i => i.level !== 'healthy').map(i => ({ asset: i.assetId, level: i.level, impactType: i.impactType, causedBy: i.causedBy }));
        return { ok: true, output: { recovered: a.assetId, wouldReturnToHealthy: restored, stillImpacted } };
      }
      case 'simulate_failure': {
        const ids = Array.isArray(args.asset_ids) ? args.asset_ids.map(String).slice(0, 5) : [];
        if (ids.length === 0) throw new Error('asset_ids required');
        for (const id of ids) if (!assets.has(id)) throw new Error(`Unknown asset '${id}'`);
        const failures = directFailures(twin);
        const before = impactTable(twin, failures);
        for (const id of ids) failures.set(id, 'offline');
        const after = impactTable(twin, failures);
        const newlyImpacted = [...after.values()]
          .filter(i => i.level !== 'healthy' && before.get(i.assetId)?.level !== i.level)
          .map(i => ({ asset: i.assetId, from: before.get(i.assetId)?.level, to: i.level, criticality: assets.get(i.assetId)?.criticality }));
        return { ok: true, output: { hypotheticalFailures: ids, newlyImpacted, note: 'Hypothetical only; no state was changed.' } };
      }
      case 'report_finding': {
        const summary = String(args.summary ?? '').trim();
        const confidence = String(args.confidence ?? '');
        if (summary.length < 5) throw new Error('summary must be at least 5 characters');
        if (!CONF.has(confidence)) throw new Error('confidence must be low, medium or high');
        const assetId = args.asset_id ? needAsset().assetId : null;
        const finding: FindingDraft = { kind: 'finding', summary: summary.slice(0, 500), evidence: String(args.evidence ?? '').slice(0, 1500), assetId, confidence: confidence as FindingDraft['confidence'] };
        return { ok: true, output: { recorded: true }, finding };
      }
      case 'recommend_recovery': {
        const a = needAsset();
        const confidence = String(args.confidence ?? '');
        if (!CONF.has(confidence)) throw new Error('confidence must be low, medium or high');
        if (a.directFailure === 'none' || a.directIncidentId !== incidentId) {
          throw new Error(`${a.assetId} is not a root-cause asset of this incident (it is ${a.impactType}); recommend recovering its root cause instead`);
        }
        const rationale = String(args.rationale ?? '').trim();
        if (rationale.length < 5) throw new Error('rationale required');
        const finding: FindingDraft = {
          kind: 'recommendation',
          summary: `Restore ${a.name}: ${rationale}`.slice(0, 500),
          evidence: String(args.evidence ?? '').slice(0, 1500),
          assetId: a.assetId,
          confidence: confidence as FindingDraft['confidence'],
        };
        return { ok: true, output: { recorded: true, note: 'Queued for human approval; not executed.' }, finding };
      }
      default:
        throw new Error(`Unknown tool '${name}'`);
    }
  } catch (err) {
    return { ok: false, output: { error: err instanceof Error ? err.message : String(err) } };
  }
}
